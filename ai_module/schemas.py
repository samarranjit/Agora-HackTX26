from typing import Literal
from pydantic import BaseModel, ConfigDict, Field, model_validator
from pydantic.alias_generators import to_camel

OptionId = Literal["a", "b", "c", "d"]


class CamelModel(BaseModel):
    """Python uses snake_case internally; JSON sent to the game uses camelCase."""
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True)


class Option(CamelModel):
    id: OptionId
    text: str


# ---------- 1. What Gemini returns (INTERNAL) ----------

class TopicList(BaseModel):
    """Result of the first query: the main topics found in the document."""
    topics: list[str] = Field(min_length=1, max_length=8)


class GeneratedChallenge(BaseModel):
    """One multiple-choice question as generated by Gemini."""
    question: str
    options: list[Option] = Field(min_length=4, max_length=4)
    correct_option_id: OptionId
    explanation: str
    mnemonic: str
    source_quote: str  # Passage from the document that supports the answer

    @model_validator(mode="after")
    def option_ids_are_a_to_d(self):
        # Reject outputs with duplicated or missing option ids
        if sorted(o.id for o in self.options) != ["a", "b", "c", "d"]:
            raise ValueError("options must have ids a, b, c, d exactly once")
        return self


class GeneratedSubject(BaseModel):
    """All challenges Gemini generates for a single topic."""
    title: str
    challenges: list[GeneratedChallenge] = Field(min_length=1)


# ---------- 2. What the server stores ----------

class StoredChallenge(BaseModel):
    """Full challenge kept server-side, including the correct answer.
    IDs (ch_1, subj_1...) are assigned by the server, not by Gemini."""
    id: str
    subject_id: str
    question: str
    options: list[Option]
    correct_option_id: OptionId
    explanation: str
    mnemonic: str
    source_quote: str
    xp_reward: int


# ---------- 3. What the game sees (PUBLIC) ----------
# None of these models has a correct-answer field, so the answer
# cannot leak to the client by accident.

class Progress(CamelModel):
    xp: int
    xp_to_unlock: int
    adventure_unlocked: bool


class PublicChallenge(CamelModel):
    id: str
    question: str
    options: list[Option]
    mnemonic: str
    xp_reward: int


class PublicSubject(CamelModel):
    id: str
    title: str
    challenges: list[PublicChallenge]


class LearningPathResponse(CamelModel):
    session_id: str
    mode: Literal["learning"] = "learning"
    subjects: list[PublicSubject]
    progress: Progress


class AnswerRequest(CamelModel):
    session_id: str
    option_id: OptionId


class AnswerResponse(CamelModel):
    """The correct answer is revealed only here, after the player answers."""
    correct: bool
    correct_option_id: OptionId
    explanation: str
    xp_awarded: int
    progress: Progress


class ErrorBody(CamelModel):
    code: str
    message: str